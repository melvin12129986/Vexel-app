-- 1. TABEL PROFILES (Terhubung dengan Supabase Auth)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  username TEXT UNIQUE NOT NULL,
  email TEXT UNIQUE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. TABEL PRODUCTS (Katalog Barang Game)
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  game TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'Skin',
  price NUMERIC NOT NULL CHECK (price >= 0),
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  min_buy INTEGER NOT NULL DEFAULT 1 CHECK (min_buy >= 1),
  image TEXT NOT NULL,
  seller TEXT NOT NULL,
  provides_proof BOOLEAN NOT NULL DEFAULT FALSE,
  "desc" TEXT NOT NULL DEFAULT '',
  rating NUMERIC DEFAULT NULL,
  rating_count INTEGER NOT NULL DEFAULT 0,
  avg_delivery TEXT NOT NULL DEFAULT '10 Menit',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. TABEL VOUCHERS (Boleh Duplikat Kode & Dihapus Saat Dipakai)
-- Jika tabel vouchers versi sebelumnya sudah ada (dengan PK code), kita sesuaikan strukturnya:
ALTER TABLE IF EXISTS public.orders DROP CONSTRAINT IF EXISTS orders_voucher_code_fkey;
DROP TABLE IF EXISTS public.vouchers CASCADE;

CREATE TABLE public.vouchers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL,
  owner_username TEXT DEFAULT NULL,
  discount_type TEXT NOT NULL CHECK (discount_type IN ('percentage', 'fixed')),
  discount_value NUMERIC NOT NULL CHECK (discount_value > 0),
  min_purchase NUMERIC NOT NULL DEFAULT 0 CHECK (min_purchase >= 0),
  max_discount NUMERIC DEFAULT NULL,
  expires_at TIMESTAMPTZ DEFAULT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. TABEL ORDERS (Transaksi & Pembayaran Midtrans)
CREATE TABLE IF NOT EXISTS public.orders (
  id TEXT PRIMARY KEY,
  product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
  product_snapshot JSONB NOT NULL,
  qty INTEGER NOT NULL CHECK (qty >= 1),
  buyer TEXT NOT NULL,
  seller TEXT NOT NULL,
  in_game_nickname TEXT NOT NULL DEFAULT '',
  wants_proof BOOLEAN NOT NULL DEFAULT FALSE,
  subtotal NUMERIC NOT NULL CHECK (subtotal >= 0),
  service_fee NUMERIC NOT NULL DEFAULT 0 CHECK (service_fee >= 0),
  proof_fee NUMERIC NOT NULL DEFAULT 0 CHECK (proof_fee >= 0),
  voucher_code TEXT DEFAULT NULL,
  voucher_discount NUMERIC NOT NULL DEFAULT 0 CHECK (voucher_discount >= 0),
  voucher_snapshot JSONB DEFAULT NULL,
  total NUMERIC NOT NULL CHECK (total >= 0),
  seller_earning NUMERIC NOT NULL DEFAULT 0 CHECK (seller_earning >= 0),
  status TEXT NOT NULL CHECK (
    status IN (
      'Menunggu Pembayaran',
      'Menunggu Pengiriman',
      'Dikirim',
      'Menunggu Penilaian',
      'Selesai'
    )
  ),
  date TEXT NOT NULL DEFAULT 'Hari ini',
  proof_image TEXT DEFAULT NULL,
  rating INTEGER DEFAULT NULL CHECK (rating IS NULL OR (rating >= 1 AND rating <= 5)),
  snap_token TEXT DEFAULT NULL,
  midtrans_transaction_status TEXT DEFAULT 'pending',
  stock_deducted BOOLEAN NOT NULL DEFAULT FALSE,
  expires_at TIMESTAMPTZ DEFAULT (NOW() + INTERVAL '24 hours'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Pastikan kolom tambahan pada orders tersedia jika tabel orders sudah dibuat sebelumnya
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS voucher_snapshot JSONB DEFAULT NULL;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS expires_at TIMESTAMPTZ DEFAULT (NOW() + INTERVAL '24 hours');

-- 5. TABEL CHAT MESSAGES (Percakapan per Order)
CREATE TABLE IF NOT EXISTS public.chat_messages (
  id TEXT PRIMARY KEY,
  order_id TEXT NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  sender TEXT NOT NULL,
  text TEXT NOT NULL,
  sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Aktifkan Realtime untuk chat_messages & orders
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND tablename = 'chat_messages'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.chat_messages;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND tablename = 'orders'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.orders;
  END IF;
END $$;

